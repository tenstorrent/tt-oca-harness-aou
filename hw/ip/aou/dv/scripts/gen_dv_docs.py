"""Generate the data-derived parts of docs/AOU_VPLAN.adoc and docs/AOU_FCOV.adoc.

The testlists, testlists/plan_ids.yaml, docs/test_plan_items.yaml, the test
and sequence class headers and the covergroup declarations are the sources;
these files are their rendering and are regenerated, never edited:

  docs/gen/vplan_summary.adoc     Scenario-Expanded Test Summary, one table
                                  per testlist (scenario, class, args, seeds,
                                  target, plan items, expected failure)
  docs/gen/vplan_procedures.adoc  Test Procedures, one per test class: purpose
                                  (the class header), procedure (its virtual
                                  sequence's header), rules it names, its
                                  scenarios and plan items
  docs/gen/vplan_matrix.adoc      Requirement-to-test matrix: every plan item
                                  with the scenarios that cite it
  docs/gen/vplan_groups.adoc      Regression groups of every testlist
  docs/gen/fcov_groups.adoc       Covergroup inventory: coverpoints and crosses
                                  per covergroup, with the component it lives in

`--check` exits 1 when a generated file differs from what the sources give
(`make lint` runs it).
"""

import argparse
import os
import re
import sys

UVM_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(UVM_ROOT, "scripts"))
import listyaml  # noqa: E402
import sim_cfg  # noqa: E402
import testlist  # noqa: E402

GEN_DIR = os.path.join(UVM_ROOT, "docs", "gen")
PLAN_ITEMS = os.path.join(UVM_ROOT, "docs", "test_plan_items.yaml")
HEADER = ("// SPDX-License-Identifier: Apache-2.0\n"
          "// SPDX-FileCopyrightText: © 2026 Tenstorrent USA Inc\n"
          "// Generated by scripts/gen_dv_docs.py from the testlists, the plan items,\n"
          "// the test and sequence class headers and the covergroups: do not edit.\n\n")
RULE_RE = re.compile(r"\b((?:AOU|APB|AXI|DP|FDI|FEAT|REG)-[RSM]\d+|T1-(?:L4A|DFT|RA|RM|LP|[CELMPTV])\d+)\b")
CLASS_RE = re.compile(r"^\s*(?:virtual\s+)?class\s+(\w+)\s+extends\s+(\w+)", re.M)
BENCH_TITLE = {"t1": "T1 (`AOU_TOP` against the layered remote-die models)",
               "reg": "Register bench (`aou_reg_top`, APB only)",
               "l3_unit": "L3 protocol-model unit bench (no DUT)",
               "axi_selftest": "AXI agent self-test bench (no DUT)"}


def cell(text):
    """One table cell's text: AsciiDoc's cell separator escaped."""
    return str(text).replace("|", "\\|")


def code(text):
    return f"`{cell(text)}`" if text else ""


def sv_files(*subdirs):
    for sub in subdirs:
        for root, dirs, files in os.walk(os.path.join(UVM_ROOT, sub)):
            dirs[:] = sorted(d for d in dirs if d != "gen")
            for name in sorted(files):
                if name.endswith((".sv", ".svh")):
                    yield os.path.join(root, name)


def header_comment(lines, idx):
    """The `//` comment block directly above line idx, as prose (one paragraph per blank
    comment line), or ''."""
    i = idx - 1
    block = []
    while i >= 0 and lines[i].strip().startswith("//"):
        block.append(lines[i].strip()[2:].strip())
        i -= 1
    block.reverse()
    while block and block[0].startswith(("SPDX-", "Copyright")):
        block.pop(0)
    while block and not block[0]:
        block.pop(0)
    return "\n".join(block)


def classes(*subdirs):
    """{class: {base, file, header, body}} over the SystemVerilog files given."""
    out = {}
    for path in sv_files(*subdirs):
        with open(path, encoding="utf-8", errors="replace") as fh:
            text = fh.read()
        lines = text.split("\n")
        for m in CLASS_RE.finditer(text):
            idx = text[:m.start()].count("\n")
            end = text.find("endclass", m.end())
            out[m.group(1)] = {"base": m.group(2), "file": os.path.relpath(path, UVM_ROOT),
                               "header": header_comment(lines, idx),
                               "body": text[m.end():end if end > 0 else m.end()]}
    return out


def prose(header):
    """A class header as AsciiDoc: plusarg lists kept as a literal block."""
    if not header:
        return "As the procedure below."
    out, lit = [], []
    for ln in header.split("\n"):
        if ln.startswith("+") or (ln.startswith(" ") and lit):
            lit.append(ln)
            continue
        if lit:
            out += ["", "----", *lit, "----", ""]
            lit = []
        out.append(ln)
    if lit:
        out += ["", "----", *lit, "----"]
    return "\n".join(out).strip()


def plan_items():
    return listyaml.load(PLAN_ITEMS)


def bench_entries():
    """{tb: [entries]} for the four benches, in testlist order."""
    plan = testlist.load_plan_ids()
    out = {}
    for tb in ("t1", "reg", "l3_unit", "axi_selftest"):
        cfg = sim_cfg.load(tb)
        path = os.path.join(UVM_ROOT, cfg["testlist"]["path"])
        out[tb] = testlist.entries(path, plan) if os.path.isfile(path) else []
    return out


def gen_summary(benches):
    out = [HEADER, "[[aou-vplan-summary-tables]]\n"]
    for tb, ents in benches.items():
        out.append(f"==== {BENCH_TITLE[tb]}\n")
        by_list = {}
        for e in ents:
            by_list.setdefault(e["list"], []).append(e)
        for lst, es in by_list.items():
            out.append(f"===== `testlists/{lst}.toml` ({len(es)} scenarios)\n")
            out.append('[cols="3,2,2,1,1,2,2",options="header"]\n|===\n'
                       "| Scenario | Test class | Arguments | Seeds | Target | Plan items | Expected failure\n")
            for e in es:
                seeds = f"{e['seeds'][0]}" if len(e["seeds"]) == 1 else f"{e['seeds'][0]}-{e['seeds'][-1]}"
                xf = e["expect_fail"]
                if e["blocked"]:
                    xf = f"blocked: {e['blocked']}"
                out.append(f"| {code(e['name'])} | {code(e['test'])} | {code(e['plusargs'])} | {seeds} | "
                           f"{code(e['target'])} | {cell(e['plan_ids'])} | {cell(xf)}\n")
            out.append("|===\n")
    return "".join(out)


def gen_groups(benches):
    out = [HEADER, "[[aou-vplan-group-tables]]\n"]
    for tb in benches:
        cfg = sim_cfg.load(tb)
        path = os.path.join(UVM_ROOT, cfg["testlist"]["path"])
        if not os.path.isfile(path):
            continue
        _, groups = testlist.load(path)
        out.append(f"==== {BENCH_TITLE[tb]}\n")
        out.append('[cols="2,1,6",options="header"]\n|===\n| Group | Scenarios | Members\n')
        for name, members in groups.items():
            shown = ", ".join(f"`{m}`" for m in members[:12])
            if len(members) > 12:
                shown += f", ... ({len(members) - 12} more)"
            out.append(f"| `{name}` | {len(members)} | {cell(shown)}\n")
        out.append("|===\n")
    return "".join(out)


def gen_procedures(benches, items):
    tests = classes("uvm/tests")
    seqs = classes("uvm/seq_lib", "uvm/env", "uvm/tests")
    title = {it["id"]: it.get("title", "") for it in items}
    out = [HEADER, "[[aou-vplan-procedure-list]]\n"]
    n = 0
    for tb, ents in benches.items():
        out.append(f"==== {BENCH_TITLE[tb]}\n")
        seen = []
        for e in ents:
            if e["test"] not in seen:
                seen.append(e["test"])
        for cls in seen:
            n += 1
            info = tests.get(cls, {"base": "?", "file": "", "header": "", "body": ""})
            es = [e for e in ents if e["test"] == cls]
            out.append(f"[[aou-proc-{cls}]]\n===== {n}. `{cls}`\n")
            out.append(f"Class `{cls}` extends `{info['base']}`"
                       + (f" (`{info['file']}`)" if info["file"] else "") + ".\n\n")
            out.append("*Purpose.* " + prose(info["header"]) + "\n\n")
            m = re.search(r'vseq_type\s*=\s*"(\w+)"', info["body"])
            rules = set(RULE_RE.findall(info["header"]))
            if m:
                vs = seqs.get(m.group(1))
                out.append(f"*Procedure.* Virtual sequence `{m.group(1)}`"
                           + (f" (`{vs['file']}`)" if vs else "") + ":\n\n")
                if vs:
                    out.append(prose(vs["header"]) + "\n\n")
                    rules |= set(RULE_RE.findall(vs["header"]))
            else:
                base = tests.get(info["base"])
                bm = re.search(r'vseq_type\s*=\s*"(\w+)"', base["body"]) if base else None
                if bm:
                    out.append(f"*Procedure.* The base class's virtual sequence `{bm.group(1)}`, "
                               f"configured by this class and its arguments.\n\n")
                else:
                    out.append("*Procedure.* The class's own `run_phase` (see the file).\n\n")
            if rules:
                out.append("*Rules named.* " + ", ".join(f"`{r}`" for r in sorted(rules)) + "\n\n")
            out.append("*Pass criteria.* The base test's end-of-test checks: scoreboard drained, every "
                       "declared expectation met, no unexpected `UVM_ERROR`/`UVM_FATAL`, the FDI checker "
                       "clean; `scripts/check_run.py` judges the log against `expected_fail.yaml`.\n\n")
            out.append("*Scenarios.*\n\n"
                       '[cols="3,2,1,1,3",options="header"]\n|===\n'
                       "| Scenario | Arguments | Seeds | Target | Plan items\n")
            pids = set()
            for e in es:
                seeds = f"{e['seeds'][0]}" if len(e["seeds"]) == 1 else f"{e['seeds'][0]}-{e['seeds'][-1]}"
                out.append(f"| {code(e['name'])} | {code(e['plusargs'])} | {seeds} | {code(e['target'])} | "
                           f"{cell(e['plan_ids'])}\n")
                pids |= set(testlist.ids(e["plan_ids"]))
            out.append("|===\n\n")
            if pids:
                out.append("*Plan items.*\n\n")
                for pid in sorted(pids, key=lambda s: [int(x) if x.isdigit() else x for x in s.split(".")]):
                    out.append(f"* {pid}: {title.get(pid, '(not in docs/test_plan_items.yaml)')}\n")
                out.append("\n")
    return "".join(out)


def gen_matrix(benches, items):
    covered = {}
    for ents in benches.values():
        for e in ents:
            for pid in testlist.ids(e["plan_ids"]):
                covered.setdefault(pid, []).append(e)
    out = [HEADER, "[[aou-vplan-matrix-table]]\n"]
    sections = {}
    for it in items:
        sections.setdefault((it.get("section", ""), it.get("section_title", "")), []).append(it)
    for (sec, sec_title), its in sections.items():
        out.append(f"==== {sec} {sec_title}\n")
        out.append('[cols="1,5,1,4",options="header"]\n|===\n| Item | Requirement | Priority | Scenarios\n')
        for it in its:
            pid = it["id"]
            if it.get("merged_into"):
                sc = f"merged into {it['merged_into']}"
            elif it.get("dropped"):
                sc = f"dropped: {it['dropped']}"
            else:
                es = covered.get(pid, [])
                names = sorted({e["name"] for e in es})
                blocked = [e for e in es if e["blocked"]]
                xf = [e for e in es if e["expect_fail"]]
                sc = ", ".join(f"`{n}`" for n in names) if names else "_none_"
                if blocked and len(blocked) == len(es):
                    sc += " (blocked)"
                elif xf and len(xf) == len(es):
                    sc += " (expected failure only)"
            out.append(f"| {pid} | {cell(it.get('title', ''))} | {cell(it.get('priority', ''))} | {cell(sc)}\n")
        out.append("|===\n")
    return "".join(out)


def covergroups():
    """[(group, component class, file, [coverpoints], [crosses])] from the SV sources."""
    out = []
    for path in sv_files("uvm/env", "cov/sv"):
        with open(path, encoding="utf-8", errors="replace") as fh:
            text = fh.read()
        comp = None
        for m in re.finditer(r"^\s*(?:class|module)\s+(\w+)|covergroup\s+(\w+)[^;]*;(.*?)endgroup", text, re.S | re.M):
            if m.group(1):
                comp = m.group(1)
                continue
            body = m.group(3)
            cps = re.findall(r"(\w+)\s*:\s*coverpoint", body)
            xs = re.findall(r"(\w+)\s*:\s*cross", body)
            out.append((m.group(2), comp or "", os.path.relpath(path, UVM_ROOT), cps, xs))
    return out


def gen_fcov_groups():
    out = [HEADER, "[[aou-fcov-group-table]]\n",
           '[cols="2,2,3,3,3",options="header"]\n|===\n| Covergroup | Component | File | Coverpoints | Crosses\n']
    for g, comp, path, cps, xs in covergroups():
        out.append(f"| `{g}` | {code(comp)} | `{path}` | {cell(', '.join(f'`{c}`' for c in cps))} | "
                   f"{cell(', '.join(f'`{x}`' for x in xs)) or '-'}\n")
    out.append("|===\n")
    return "".join(out)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="exit 1 when a generated file is stale")
    ap.add_argument("--out-dir", default=GEN_DIR)
    args = ap.parse_args(argv)

    benches = bench_entries()
    items = plan_items()
    files = {
        "vplan_summary.adoc": gen_summary(benches),
        "vplan_groups.adoc": gen_groups(benches),
        "vplan_procedures.adoc": gen_procedures(benches, items),
        "vplan_matrix.adoc": gen_matrix(benches, items),
        "fcov_groups.adoc": gen_fcov_groups(),
    }
    stale = []
    os.makedirs(args.out_dir, exist_ok=True)
    for name, text in files.items():
        path = os.path.join(args.out_dir, name)
        old = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if old != text:
            stale.append(name)
            if not args.check:
                with open(path, "w", encoding="utf-8") as fh:
                    fh.write(text)
    if args.check:
        if stale:
            print("gen_dv_docs: stale: " + ", ".join(stale) + "; run `make docs`", file=sys.stderr)
            return 1
        print("gen_dv_docs: docs/gen up to date")
        return 0
    print(f"gen_dv_docs: wrote {len(files)} file(s) to {os.path.relpath(args.out_dir, UVM_ROOT)}"
          + (f" ({len(stale)} changed)" if stale else " (no change)"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
