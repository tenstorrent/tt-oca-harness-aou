# Regenerate the committed UVM register model uvm/env/gen/aou_core_csr_uvm_pkg.sv
# from the unmodified csr/aou-core.rdl with the PeakRDL the repository pins
# (make setup installs it under .deps/peakrdl). The model is committed so the
# bench compiles from a plain checkout, standalone or vendored into
# tt-oca-harness, without a Python step in the build; `make lint` runs this with
# --check and fails when the RDL has moved on without it.
#
#   scripts/regen_ral.sh          rewrite the model
#   scripts/regen_ral.sh --check  exit 1 (with a diff) if the committed model is stale
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ROOT="$(cd "$HERE/../../../.." && pwd)"
RDL="$ROOT/csr/aou-core.rdl"
OUT="$HERE/uvm/env/gen/aou_core_csr_uvm_pkg.sv"
PEAKRDL="${PEAKRDL:-$HERE/.deps/peakrdl/bin/peakrdl}"
[[ -x "$PEAKRDL" ]] || { echo "regen_ral: $PEAKRDL not found; run make setup" >&2; exit 1; }

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
# PeakRDL names the package after the output file.
"$PEAKRDL" uvm "$RDL" -o "$TMP/aou_core_csr_uvm_pkg.sv"
{
  echo "// SPDX-License-Identifier: Apache-2.0"
  echo "// SPDX-FileCopyrightText: © 2026 Tenstorrent USA Inc"
  echo "//"
  echo "// Generated by hw/ip/aou/dv/scripts/regen_ral.sh from csr/aou-core.rdl: do not edit."
  echo "// \`make ral\` regenerates it; \`make lint\` fails when it is stale."
  cat "$TMP/aou_core_csr_uvm_pkg.sv"
} > "$TMP/with_header.sv"

if [[ "${1:-}" == "--check" ]]; then
  if [[ ! -f "$OUT" ]]; then
    echo "regen_ral: $OUT is missing; run make ral" >&2
    exit 1
  fi
  if ! diff -u "$OUT" "$TMP/with_header.sv"; then
    echo "regen_ral: $OUT is stale against csr/aou-core.rdl; run make ral" >&2
    exit 1
  fi
  echo "regen_ral: $OUT is current"
  exit 0
fi
mkdir -p "$(dirname "$OUT")"
mv -f "$TMP/with_header.sv" "$OUT"
echo "regen_ral: wrote $OUT"
