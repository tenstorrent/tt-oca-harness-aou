"""Generate docs/test_plan_items.yaml from the old test plan plus corrections.

The old plan is the verification branch's dv/doc/AOU_RTL_TEST_PLAN.md
(sections 2.1-2.22; item N.M sits in section 2.N). Each table row becomes one
item: id, section, title (the Description column), priority, and the old test
file and status columns. docs/test_plan_corrections.yaml then rewords items
(`title`), merges duplicates (`merged_into`), drops obsolete items
(`dropped`), or adds new items, each with a `note`. A new item is either
`add: yes` with `title` and `priority`, or `added` naming its source, plus
`title` and `priority`; either joins section 2.N after its last item. Edit the
corrections, never the output.

  git show verification:dv/doc/AOU_RTL_TEST_PLAN.md > old_plan.md
  scripts/gen_plan_items.py old_plan.md            # rewrites docs/test_plan_items.yaml
  scripts/gen_plan_items.py old_plan.md --check    # exit 1 if the file is stale
"""

import argparse
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import listyaml  # noqa: E402

UVM_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
KEYS = ["id", "section", "section_title", "title", "priority", "old_test", "old_status",
        "added", "merged_into", "dropped", "old_title", "note"]
HEADER = """\
# SPDX-License-Identifier: Apache-2.0
# SPDX-FileCopyrightText: © 2026 Tenstorrent USA Inc
#
# Test-plan items: generated by scripts/gen_plan_items.py from the old plan
# (verification branch, dv/doc/AOU_RTL_TEST_PLAN.md, sections 2.1-2.22) and
# docs/test_plan_corrections.yaml. Do not edit; change the corrections and
# regenerate. Item N.M is in section 2.N. merged_into: the item is a duplicate
# and reports through that ID. dropped: not testable on this RTL. added: an item
# the old plan lacked, with its source. old_test and old_status are the old
# plan's Test File and Status columns."""


def parse_plan(path):
    items, sec, sec_title = [], None, None
    with open(path, encoding="utf-8") as fh:
        for line in fh:
            m = re.match(r"^###\s+(2\.\d+)\s+(.*?)\s*$", line)
            if m:
                sec, sec_title = m.group(1), m.group(2)
                continue
            if re.match(r"^##\s", line):
                sec = None
            if sec is None or not re.match(r"^\|\s*\d+\.\d+\s*\|", line):
                continue
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            if len(cells) == 6:
                iid, test, desc, _goal, pri, status = cells
            elif len(cells) == 5:  # 16.16 has no Test File column
                iid, desc, _goal, pri, status = cells
                test = ""
            else:
                sys.exit(f"{path}: unexpected row: {line.strip()}")
            if iid.split(".")[0] != sec.split(".")[1]:
                sys.exit(f"{path}: item {iid} under section {sec}")
            items.append({
                "id": iid, "section": sec, "section_title": sec_title,
                "title": re.sub(r"\*\*(.*?)\*\*", r"\1", desc),
                "priority": pri, "old_test": test or None, "old_status": status or None,
            })
    return items


def id_key(iid):
    return tuple(int(x) for x in iid.split("."))


def add_item(items, by_id, c, errors):
    """A new item from an `added` correction, placed after its section's last item."""
    iid = c["id"]
    sec = "2." + iid.split(".")[0]
    peers = [k for k, i in enumerate(items) if i["section"] == sec]
    if not peers or not c.get("title") or not c.get("priority"):
        errors.append(f"added item {iid}: unknown section {sec}, or no title or priority")
        return None
    if any(id_key(items[k]["id"]) > id_key(iid) for k in peers):
        errors.append(f"added item {iid} does not follow its section's last item")
        return None
    item = {"id": iid, "section": sec, "section_title": items[peers[0]]["section_title"],
            "title": c["title"], "priority": c["priority"], "old_test": None, "old_status": None,
            "added": c["added"]}
    items.insert(peers[-1] + 1, item)
    by_id[iid] = item
    return item


def add_items(items, corrections):
    """Insert the `add: yes` corrections as new items; returns the errors."""
    errors = []
    for c in corrections:
        if c.get("add") != "yes":
            continue
        iid = c.get("id", "")
        sec = "2." + iid.split(".")[0]
        if any(i["id"] == iid for i in items):
            errors.append(f"added item {iid} already exists")
            continue
        if not c.get("title") or not c.get("priority") or not c.get("note"):
            errors.append(f"added item {iid} needs title, priority and note")
            continue
        pos = [n for n, i in enumerate(items) if i["section"] == sec]
        if not pos:
            errors.append(f"added item {iid}: no section {sec}")
            continue
        items.insert(pos[-1] + 1, {"id": iid, "section": sec,
                                   "section_title": items[pos[-1]]["section_title"],
                                   "title": c["title"], "priority": c["priority"],
                                   "note": c["note"]})
    return errors


def apply_corrections(items, corrections):
    errors = add_items(items, corrections)
    by_id = {i["id"]: i for i in items}
    for c in corrections:
        if c.get("add") == "yes":
            continue
        item = by_id.get(c.get("id"))
        if item is None and "added" in c:
            item = add_item(items, by_id, c, errors)
            if item is None:
                continue
            if not c.get("note"):
                errors.append(f"correction for {c['id']} has no note")
            item["note"] = c.get("note")
            continue
        if item is None:
            errors.append(f"correction for unknown item {c.get('id')}")
            continue
        if "added" in c:
            errors.append(f"added item {c['id']} already exists")
            continue
        if not c.get("note"):
            errors.append(f"correction for {c['id']} has no note")
        if "title" in c:
            item["old_title"], item["title"] = item["title"], c["title"]
        for k in ("merged_into", "dropped", "priority", "note"):
            if k in c:
                item[k] = c[k]
    for item in items:
        tgt = item.get("merged_into")
        if tgt and (tgt not in by_id or by_id[tgt].get("merged_into") or by_id[tgt].get("dropped")):
            errors.append(f"{item['id']} merged into {tgt}, which is missing, merged or dropped")
    return errors


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("plan", help="old AOU_RTL_TEST_PLAN.md")
    ap.add_argument("--corrections", default=os.path.join(UVM_ROOT, "docs", "test_plan_corrections.yaml"))
    ap.add_argument("-o", "--output", default=os.path.join(UVM_ROOT, "docs", "test_plan_items.yaml"))
    ap.add_argument("--check", action="store_true", help="compare with the output instead of writing it")
    args = ap.parse_args()

    items = parse_plan(args.plan)
    if not items:
        sys.exit(f"{args.plan}: no test-plan items found")
    errors = apply_corrections(items, listyaml.load(args.corrections))
    if errors:
        sys.exit("\n".join(errors))
    text = listyaml.dump(items, KEYS, HEADER)
    if args.check:
        with open(args.output, encoding="utf-8") as fh:
            same = fh.read() == text
        print(f"{args.output}: {'up to date' if same else 'stale; regenerate'}")
        return 0 if same else 1
    with open(args.output, "w", encoding="utf-8") as fh:
        fh.write(text)
    merged = sum(1 for i in items if i.get("merged_into"))
    dropped = sum(1 for i in items if i.get("dropped"))
    added = sum(1 for i in items if i.get("added"))
    print(f"{len(items)} items ({merged} merged, {dropped} dropped, {added} added) -> {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
